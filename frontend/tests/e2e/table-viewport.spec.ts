import { expect, test } from '@playwright/test'

for (const viewport of [{ width: 1560, height: 980 }, { width: 1280, height: 800 }, { width: 720, height: 900 }, { width: 390, height: 844 }]) {
  test(`sticky headers, key column and parent scrolling at ${viewport.width}px`, async ({ page }) => {
    await page.setViewportSize(viewport)
    await page.goto('/tests/fixtures/table-viewport.html')

    const local = page.getByLabel('长表格本地滚动')
    const localHeader = local.locator('thead th').first()
    const localKey = local.locator('tbody tr').first().locator('td').first()
    await expect(local).toBeVisible()
    const localGeometry = await local.evaluate(el => ({ clientHeight: el.clientHeight, scrollHeight: el.scrollHeight, clientWidth: el.clientWidth, scrollWidth: el.scrollWidth }))
    expect(localGeometry.scrollHeight).toBeGreaterThan(localGeometry.clientHeight)
    expect(localGeometry.scrollWidth).toBeGreaterThan(localGeometry.clientWidth)
    await local.evaluate(el => { el.scrollTop = 250; el.scrollLeft = 120 })
    const sticky = await localHeader.boundingBox()
    const key = await localKey.boundingBox()
    const localBox = await local.boundingBox()
    expect(sticky!.y).toBeGreaterThanOrEqual(localBox!.y - 1)
    expect(sticky!.y).toBeLessThanOrEqual(localBox!.y + 2)
    expect(key!.x).toBeGreaterThanOrEqual(localBox!.x - 1)
    expect(key!.x).toBeLessThanOrEqual(localBox!.x + 2)
    const selected = local.locator('tbody tr').first()
    await selected.hover({ force: true })
    const backgrounds = await selected.locator('td').evaluateAll(cells => cells.slice(0, 2).map(cell => getComputedStyle(cell).backgroundColor))
    expect(backgrounds[0]).toBe(backgrounds[1])
    expect(backgrounds[0]).toBe('rgb(234, 242, 255)')

    const panel = page.getByLabel('任务报告滚动面板')
    const parentTable = page.getByLabel('父面板滚动报告表格')
    const reportHeader = parentTable.locator('thead th').first()
    const panelBefore = await panel.evaluate(el => ({ scrollHeight: el.scrollHeight, clientHeight: el.clientHeight }))
    expect(panelBefore.scrollHeight).toBeGreaterThan(panelBefore.clientHeight)
    const wrapperMetrics = await parentTable.evaluate(el => ({ scrollWidth: el.scrollWidth, clientWidth: el.clientWidth, scrollHeight: el.scrollHeight, clientHeight: el.clientHeight }))
    expect(wrapperMetrics.scrollWidth).toBeLessThanOrEqual(wrapperMetrics.clientWidth + 1)
    expect(wrapperMetrics.scrollHeight).toBeLessThanOrEqual(wrapperMetrics.clientHeight + 1)
    const panelBox = await panel.boundingBox()
    await panel.evaluate(el => { el.scrollTop = 220 })
    const reportHeaderBox = await reportHeader.boundingBox()
    expect(reportHeaderBox!.y).toBeGreaterThanOrEqual(panelBox!.y - 1)
    expect(reportHeaderBox!.y).toBeLessThanOrEqual(panelBox!.y + 2)
    const reportText = await parentTable.locator('tbody td').nth(2).boundingBox()
    expect(reportText!.width).toBeLessThanOrEqual(wrapperMetrics.clientWidth + 1)
    const documentWidth = await page.evaluate(() => document.documentElement.scrollWidth)
    expect(documentWidth).toBeLessThanOrEqual(viewport.width)
    const market = page.getByLabel('市场报告滚动面板')
    await market.scrollIntoViewIfNeeded()
    await market.evaluate(el => { el.scrollTop = 250 })
    const marketBox = await market.boundingBox()
    const marketHeaderBox = await market.locator('thead th').first().boundingBox()
    expect(marketHeaderBox!.y).toBeGreaterThanOrEqual(marketBox!.y - 1)
    expect(marketHeaderBox!.y).toBeLessThanOrEqual(marketBox!.y + 2)
  })
}
